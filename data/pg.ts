export function getPGBySlug(slug: string): PG | undefined {
  return pgs.find((pg) => pg.slug === slug);
}

export function getSimilarPGs(pg: PG, count = 3): PG[] {
  const sameCity = pgs.filter((p) => p.id !== pg.id && p.city === pg.city);
  const sameGender = pgs.filter(
    (p) => p.id !== pg.id && p.city !== pg.city && p.gender === pg.gender
  );
  return [...sameCity, ...sameGender].slice(0, count);
}
